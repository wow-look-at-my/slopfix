package gitread

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

// The cases come from git's t3070-wildmatch.sh, with the path-name flag on.
func TestWildmatchAgreesWithGit(t *testing.T) {
	cases := []struct {
		pattern, text string
		match         bool
	}{
		{"foo", "foo", true},
		{"bar", "foo", false},
		{"", "", true},
		{"???", "foo", true},
		{"??", "foo", false},
		{"*", "foo", true},
		{"f*", "foo", true},
		{"*f", "foo", false},
		{"*foo*", "foo", true},
		{"*ob*a*r*", "foobar", true},
		{"*ab", "aaaaaaabababab", true},
		{`foo\*`, "foo*", true},
		{`foo\*bar`, "foobar", false},
		{`f\\oo`, `f\oo`, true},
		{"*[al]?", "ball", true},
		{"[ten]", "ten", false},
		{"**[!te]", "ten", true},
		{"**[!ten]", "ten", false},
		{"t[a-g]n", "ten", true},
		{"t[!a-g]n", "ten", false},
		{"t[!a-g]n", "ton", true},
		{"t[^a-g]n", "ton", true},
		{"a[]]b", "a]b", true},
		{"a[]-]b", "a-b", true},
		{"a[]a-]b", "aab", true},
		{"]", "]", true},
		{"foo*bar", "foo/baz/bar", false},
		{"foo**bar", "foo/baz/bar", false},
		{"foo**bar", "foobazbar", true},
		{"foo/**/bar", "foo/baz/bar", true},
		{"foo/**/**/bar", "foo/baz/bar", true},
		{"foo/**/bar", "foo/b/a/z/bar", true},
		{"foo/**/bar", "foo/bar", true},
		{"foo/**/**/bar", "foo/bar", true},
		{"foo?bar", "foo/bar", false},
		{"foo[/]bar", "foo/bar", false},
		{"foo[^a-z]bar", "foo/bar", false},
		{"f[^eiu][^eiu][^eiu][^eiu][^eiu]r", "foo/bar", false},
		{"f[^eiu][^eiu][^eiu][^eiu][^eiu]r", "foo-bar", true},
		{"**/foo", "foo", true},
		{"**/foo", "XXX/foo", true},
		{"**/foo", "bar/baz/foo", true},
		{"*/foo", "bar/baz/foo", false},
		{"**/bar*", "foo/bar/baz", false},
		{"**/bar/*", "deep/foo/bar/baz", true},
		{"**/bar/*", "deep/foo/bar/baz/", false},
		{"**/bar/**", "deep/foo/bar/baz/", true},
		{"**/bar/*", "deep/foo/bar", false},
		{"**/bar/**", "deep/foo/bar/", true},
		{"**/bar**", "foo/bar/baz", false},
		{"*/bar/**", "foo/bar/baz/x", true},
		{"*/bar/**", "deep/foo/bar/baz/x", false},
		{"**/bar/*/*", "deep/foo/bar/baz/x", true},
		{"a[c-c]st", "acrt", false},
		{"a[c-c]rt", "acrt", true},
		{"[!]-]", "]", false},
		{"[!]-]", "a", true},
		{`\`, "", false},
		{`*/\`, `XXX/\`, false},
		{`*/\\`, `XXX/\`, true},
		{"foo", "foo", true},
		{"@foo", "@foo", true},
		{"@foo", "foo", false},
		{`\[ab]`, "[ab]", true},
		{"[[]ab]", "[ab]", true},
		{"[[:]ab]", "[ab]", true},
		{"[[::]ab]", "[ab]", false},
		{"[[:digit]ab]", "[ab]", true},
		{`[\[:]ab]`, "[ab]", true},
		{`\??\?b`, "?a?b", true},
		{`\a\b\c`, "abc", true},
		{"[[:alpha:]][[:digit:]][[:upper:]]", "a1B", true},
		{"[[:digit:][:upper:][:space:]]", "a", false},
		{"[[:digit:][:upper:][:space:]]", "A", true},
		{"[[:digit:][:upper:][:space:]]", "1", true},
		{"[[:digit:][:upper:][:space:]]", " ", true},
		{"[[:digit:][:upper:][:space:]]", ".", false},
		{"[[:digit:][:punct:][:space:]]", ".", true},
		{"[a-c[:digit:]x-z]", "5", true},
		{"[a-c[:digit:]x-z]", "b", true},
		{"[a-c[:digit:]x-z]", "y", true},
		{"[a-c[:digit:]x-z]", "q", false},
		{"-*-*-*-*-*-*-12-*-*-*-m-*-*-*", "-adobe-courier-bold-o-normal--12-120-75-75-m-70-iso8859-1", true},
		{"-*-*-*-*-*-*-12-*-*-*-m-*-*-*", "-adobe-courier-bold-o-normal--12-120-75-75-X-70-iso8859-1", false},
		{"XXX/*/*/*/*/*/*/12/*/*/*/m/*/*/*", "XXX/adobe/courier/bold/o/normal//12/120/75/75/m/70/iso8859/1", true},
		{"**/*a*b*g*n*t", "abcd/abcdefg/abcdefghijk/abcdefghijklmnop.txt", true},
		{"**/*a*b*g*n*t", "abcd/abcdefg/abcdefghijk/abcdefghijklmnop.txtz", false},
		{"*/*/*", "foo", false},
		{"*/*/*", "foo/bar", false},
		{"*/*/*", "foo/bba/arr", true},
		{"*/*/*", "foo/bb/aa/rr", false},
		{"**/**/**", "foo/bb/aa/rr", true},
		{"*X*i", "abcXdefXghi", true},
		{"*X*i", "ab/cXd/efXg/hi", false},
		{"*/*X*/*/*i", "ab/cXd/efXg/hi", true},
		{"**/*X*/**/*i", "ab/cXd/efXg/hi", true},
	}
	for _, c := range cases {
		assert.Equal(t, c.match, wildmatch(c.pattern, c.text, true, false), "%q against %q", c.pattern, c.text)
	}
	assert.True(t, wildmatch("*.GO", "x.go", true, true), "a folded match ignores case")
	assert.True(t, wildmatch("a*b", "a/x/b", false, false), "without the path-name flag a wildcard crosses a slash")
}
