// Package gen reads the rule XML and writes the Go a consumer compiles.
//
// The folder is the table: every .xml in it is loaded, and a file says which
// consumer it belongs to with the `for` attribute on its root. Order is file
// name order and then document order, so a longer phrase that must beat a
// shorter phrase sits above it.
package gen

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/wow-look-at-my/slopfix/table"
)

// Request is a single generated table: which rules to read, and where to put
// the Go.
type Request struct {
	// Rules is the folder holding the XML.
	Rules string
	// Target is the `for` value to collect.
	Target string
	// Package is the package clause the generated files carry.
	Package string
	// Out is the table file to write.
	Out string
	// Dir is where the compiled matchers go, beside the table.
	Dir string
}

// Run writes the table and the matchers behind it.
func Run(req Request) error {
	loaded, err := Load(req.Rules, req.Target)
	if err != nil {
		return err
	}
	if loaded.empty() {
		return fmt.Errorf("no entry in %s carries for=%q", req.Rules, req.Target)
	}
	for i := range loaded.Patterns {
		if err := compilePattern(req, i, &loaded.Patterns[i]); err != nil {
			return err
		}
	}
	return os.WriteFile(req.Out, []byte(render(req, loaded)), 0o644)
}

// compilePattern turns a <pattern> into the matchers the driver calls.
//
// A DFA cannot read the byte outside a match, so a word boundary at either end
// is stripped here and carried on the entry instead. An interior boundary has
// no such home, and guessing at it would write a matcher that quietly
// disagrees with the pattern the table states.
func compilePattern(req Request, i int, p *Pattern) error {
	bare, lead, tail, err := stripBoundaries(p.Match)
	if err != nil {
		return fmt.Errorf("<pattern match=%q>: %w", p.Match, err)
	}
	p.LeadWord, p.TailWord = lead, tail
	p.Prefix = fmt.Sprintf("%sPat%d", req.Target, i)

	// The prefilter answers the whole string in a single pass.
	if err := regexCompiler(req, regexJob{
		Regex: bare,
		Mode:  "contains",
		Func:  p.Prefix + "Has",
		Out:   filepath.Join(req.Dir, strings.ToLower(p.Prefix)+"_has.gen.go"),
	}); err != nil {
		return fmt.Errorf("<pattern match=%q>: %w", p.Match, err)
	}
	return regexCompiler(req, regexJob{
		Regex:    "(?s)(" + bare + ")(?s:.*)",
		Mode:     "full",
		Func:     p.Prefix + "At",
		Submatch: p.Prefix + "Find",
		Names:    p.Prefix + "Names",
		Out:      filepath.Join(req.Dir, strings.ToLower(p.Prefix)+"_at.gen.go"),
	})
}

// render writes the generated table.
func render(req Request, t *Loaded) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by cmd/rulegen from %s. DO NOT EDIT.\n\n", req.Rules)
	fmt.Fprintf(&b, "package %s\n\n", req.Package)
	b.WriteString("import \"github.com/wow-look-at-my/slopfix/table\"\n\n")
	fmt.Fprintf(&b, "// %sTable is what rules/ says for=%q, in file name order.\n",
		req.Target, req.Target)
	fmt.Fprintf(&b, "var %sTable = table.Table{\n", req.Target)

	b.WriteString("\tDrops: []table.Drop{\n")
	for _, d := range t.Drops {
		fmt.Fprintf(&b, "\t\t{ID: %s, Word: %s, Where: %s, Tests: %s},\n",
			q(d.ID), q(d.Word), q(d.Where), tests(d.Tests))
	}
	b.WriteString("\t},\n\tRewrites: []table.Rewrite{\n")
	for _, r := range t.Rewrites {
		fmt.Fprintf(&b, "\t\t{ID: %s, From: %s, To: %s, Where: %s, Tests: %s},\n",
			q(r.ID), q(r.From), q(r.To), q(r.Where), tests(r.Tests))
	}
	b.WriteString("\t},\n\tPatterns: []table.Pattern{\n")
	for _, p := range t.Patterns {
		fmt.Fprintf(&b, "\t\t{\n\t\t\tID: %s, Match: %s, To: %s, Where: %s,\n",
			q(p.ID), q(p.Match), q(p.To), q(p.Where))
		fmt.Fprintf(&b, "\t\t\tTests: %s,\n", tests(p.Tests))
		fmt.Fprintf(&b, "\t\t\tHas: %sHas, At: %sAt, Find: %sFindIndex,\n", p.Prefix, p.Prefix, p.Prefix)
		fmt.Fprintf(&b, "\t\t\tLeadWord: %t, TailWord: %t,\n\t\t},\n", p.LeadWord, p.TailWord)
	}
	b.WriteString("\t},\n\tFlags: []table.Flag{\n")
	for _, f := range t.Flags {
		fmt.Fprintf(&b, "\t\t{ID: %s, Phrase: %s, Say: %s, Tests: %s},\n",
			q(f.ID), q(f.Phrase), q(f.Say), tests(f.Tests))
	}
	b.WriteString("\t},\n\tClasses: []table.Class{\n")
	for _, c := range t.Classes {
		fmt.Fprintf(&b, "\t\t{Name: %s, Words: %s, Suffix: %s, Open: %t, Except: %s},\n",
			q(c.Name), words(c.Words), words(c.Suffix), c.Open, words(c.Except))
	}
	b.WriteString("\t},\n\tNormals: []table.Normalize{\n")
	for _, n := range t.Normals {
		fmt.Fprintf(&b, "\t\t{ID: %s, From: %s, To: %s, Tests: %s},\n",
			q(n.ID), q(n.From), q(n.To), tests(n.Tests))
	}
	b.WriteString("\t},\n\tRephrasings: []table.Rephrase{\n")
	for _, r := range t.Rephrases {
		fmt.Fprintf(&b, "\t\t{\n\t\t\tID: %s, Match: %s, To: %s, Where: %s,\n",
			q(r.ID), q(r.Match), q(r.To), q(r.Where))
		fmt.Fprintf(&b, "\t\t\tTests: %s,\n", tests(r.Tests))
		fmt.Fprintf(&b, "\t\t\tTerms: %s,\n\t\t},\n", renderTerms(r.Match))
	}
	b.WriteString("\t},\n}\n")
	renderAlternations(&b, req, t)
	return b.String()
}

// renderTerms writes a parsed match as a literal. Load has already refused a
// match that does not parse, so this cannot fail here.
func renderTerms(match string) string {
	parsed, err := table.ParseMatch(match)
	if err != nil {
		return "table.Match{}"
	}
	var b strings.Builder
	b.WriteString("table.Match{Terms: []table.Term{")
	for i, t := range parsed.Terms {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "{Classes: %s, Word: %s, Name: %s, Many: %t}",
			list(t.Classes), q(t.Word), q(t.Name), t.Many)
	}
	b.WriteString("}}")
	return b.String()
}

// tests renders an entry's cases as a Go literal.
func tests(cases []Test) string {
	if len(cases) == 0 {
		return "nil"
	}
	var b strings.Builder
	b.WriteString("[]table.Test{")
	for i, c := range cases {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "{In: %s, Out: %s}", q(c.In), q(c.Out))
	}
	b.WriteString("}")
	return b.String()
}

// list renders a slice of strings as a Go literal.
func list(items []string) string {
	if len(items) == 0 {
		return "nil"
	}
	var b strings.Builder
	b.WriteString("[]string{")
	for i, s := range items {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(q(s))
	}
	b.WriteString("}")
	return b.String()
}

// words renders a whitespace-separated attribute as a Go slice literal.
func words(list string) string {
	fields := strings.Fields(list)
	if len(fields) == 0 {
		return "nil"
	}
	var b strings.Builder
	b.WriteString("[]string{")
	for i, f := range fields {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(q(f))
	}
	b.WriteString("}")
	return b.String()
}

// q quotes a string as Go source.
func q(s string) string { return strconv.Quote(s) }

// renderAlternations writes one constant per class holding its words as a
// regular expression alternation. The words are known while this runs, so the
// join belongs here: a caller building a pattern out of one keeps a constant,
// and nothing assembles the same string again at startup.
func renderAlternations(b *strings.Builder, req Request, t *Loaded) {
	var named []table.Class
	for _, c := range t.Classes {
		if len(c.Words) > 0 {
			named = append(named, c)
		}
	}
	if len(named) == 0 {
		return
	}
	fmt.Fprintf(b, "\n// Each class of %s as an alternation, for a pattern to embed.\nconst (\n", req.Target)
	for _, c := range named {
		quoted := make([]string, len(c.Words))
		for i, w := range c.Words {
			quoted[i] = regexp.QuoteMeta(w)
		}
		fmt.Fprintf(b, "\t%sAlt%s = %s\n", req.Target, exportedName(c.Name), q(strings.Join(quoted, "|")))
	}
	b.WriteString(")\n")
}

// exportedName spells a class name as a Go identifier fragment, so a name
// carrying a hyphen still reads as one word in the constant it names.
func exportedName(name string) string {
	var out strings.Builder
	upper := true
	for _, r := range name {
		if r == '-' || r == '_' || r == ' ' {
			upper = true
			continue
		}
		if upper {
			out.WriteString(strings.ToUpper(string(r)))
			upper = false
			continue
		}
		out.WriteRune(r)
	}
	return out.String()
}

// stripBoundaries removes a leading and a trailing \b and reports which it
// took. An interior boundary is an error: see compilePattern.
func stripBoundaries(match string) (bare string, lead, tail bool, err error) {
	bare = match
	// The flag group rides ahead of the boundary, as in `(?i)\bone`.
	flags := ""
	if strings.HasPrefix(bare, "(?") {
		if end := strings.IndexByte(bare, ')'); end > 0 && !strings.Contains(bare[:end], ":") {
			flags, bare = bare[:end+1], bare[end+1:]
		}
	}
	if rest, found := strings.CutPrefix(bare, `\b`); found {
		bare, lead = rest, true
	}
	if rest, found := strings.CutSuffix(bare, `\b`); found {
		bare, tail = rest, true
	}
	if strings.Contains(bare, `\b`) || strings.Contains(bare, `\B`) {
		return "", false, false, fmt.Errorf(
			"a word boundary sits inside the pattern, where a compiled matcher cannot read the byte beside it")
	}
	return flags + bare, lead, tail, nil
}

// sortedXML lists the folder's files in the order their entries are collected.
func sortedXML(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".xml") {
			out = append(out, filepath.Join(dir, entry.Name()))
		}
	}
	sort.Strings(out)
	return out, nil
}
