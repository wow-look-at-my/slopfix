// Command gen writes regexps.gen.go: a constant regexp.MustCompile call for
// each pattern that slopfix builds from data. The compiler precompiles a
// constant pattern, so the binary compiles none of these at run time.
//
// It imports the whole program. Every table loads at package init, so each
// pattern that precompiled.MustCompile serves is requested by the time main
// runs.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strconv"

	_ "github.com/wow-look-at-my/slopfix/cmd"
	"github.com/wow-look-at-my/slopfix/precompiled"
)

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by precompiled/internal/gen. DO NOT EDIT.\n\n")
	b.WriteString("package precompiled\n\nimport \"regexp\"\n\nfunc init() {\n")
	for _, pattern := range precompiled.Requested() {
		needs := "nil"
		if set := precompiled.Required(pattern); set != nil {
			needs = "[]string{"
			for i, s := range set {
				if i > 0 {
					needs += ", "
				}
				needs += strconv.Quote(s)
			}
			needs += "}"
		}
		fmt.Fprintf(&b, "\tadd(regexp.MustCompile(%s), %s)\n", strconv.Quote(pattern), needs)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile("regexps.gen.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}
