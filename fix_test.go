// A named ID repairs that rule and leaves its siblings alone, which is what
// makes an ID worth naming at all.
func TestANamedIDRepairsThatRuleAlone(t *testing.T) {
	doc := "It should work; that is fine, we can't stop.\n"

	semicolon := slopfix.Fix(slopfix.Request{
		Content: doc,
		Rules:   []slopfix.Rule{slopfix.RuleEnglish},
		IDs:     []string{"english/semicolon"},
	})
	contraction := slopfix.Fix(slopfix.Request{
		Content: doc,
		Rules:   []slopfix.Rule{slopfix.RuleSTE},
		IDs:     []string{"ste/contraction"},
	})

	// Each named ID repairs the document, and both answers differ.
	assert.NotEqual(t, doc, semicolon.Text)
	assert.NotEqual(t, doc, contraction.Text)
	assert.NotEqual(t, semicolon.Text, contraction.Text)
}

// A finding outside the named ID is neither repaired nor reported, so a caller
// that asks for a rule is not handed the rest of the category. The named rule
// itself is repaired and reports nothing afterwards.
func TestANamedIDLeavesTheRestOfItsCategoryAlone(t *testing.T) {
	doc := "There are three sections; each is read.\n"
	repair := slopfix.Fix(slopfix.Request{
		Content: doc,
		Rules:   []slopfix.Rule{slopfix.RuleCounts},
		IDs:     []string{"counts/stated-count"},
	})

	// The count is repaired, the semicolon beside it is left standing.
	assert.NotEmpty(t, repair.Removed)
	assert.Contains(t, repair.Text, ";")
	assert.Empty(t, repair.Findings)
}

// Naming an ID keeps every other rule's repair off the file, the whole-line
// strip included. A caller that asked for a number repair and got a deleted
// doc line has had another rule applied to it unasked.
func TestANamedIDKeepsTheWholeLineStripOff(t *testing.T) {
	src := "// Add inserts elem. It returns true when the element was added,\n" +
		"// or false when it was already present.\nfunc Add() {}\n"

	repair := slopfix.Fix(slopfix.Request{
		Content: src,
		Path:    "set.go",
		IDs:     []string{"comments/number"},
	})
	assert.Equal(t, src, repair.Text, "no number is stated here, so nothing changes")
}

// Sentences from a real document, each of which a count cut once left saying
// something false or ungrammatical. A duration, a status code, a partitive and
// a sentence-initial cut each keep what the reader needs.
func TestACountCutLeavesTheSentenceTrue(t *testing.T) {
	for _, c := range []struct {
		in        string
		forbidden string
	}{
		{"So readiness is its own statement, re-checked every 15 minutes, and logged at startup.\n", "every minutes"},
		{"No caller can fix that, and a 404 buries it.\n", "a buries"},
		{"Inside those namespaces a caller needs one of two things.\n", "one of things"},
		{"Either of the other two confirms the module exists.\n", "the other confirms"},
	} {
		t.Run(c.in, func(t *testing.T) {
			repair := prose(c.in)
			assert.NotContains(t, repair.Text, c.forbidden)
		})
	}
}

// A cut at the front of a sentence leaves the next word to start it.
func TestACountCutAtTheStartCapitalizesWhatFollows(t *testing.T) {
	for _, in := range []string{
		"Two defects compounded, and the reader saw neither.\n",
		"Two ambiguities are resolved deliberately here.\n",
	} {
		t.Run(in, func(t *testing.T) {
			repair := prose(in)
			require.NotEmpty(t, repair.Text)
			first := []rune(repair.Text)[0]
			assert.False(t, first >= 'a' && first <= 'z', "sentence starts lowercase: %q", repair.Text)
		})
	}
}

func TestEveryCategoryNamesItsRules(t *testing.T) {
	for _, rule := range slopfix.AllRules {
		ids := slopfix.IDsFor(rule)
		assert.False(t, ids.IsEmpty(), "%s names no rule", rule)
		for id := range ids.All() {
			assert.True(t, strings.HasPrefix(id, string(rule)+"/"), "%s is not under %s", id, rule)
		}
	}
	assert.True(t, slopfix.IDsFor(slopfix.Rule("nosuch")).IsEmpty())
}
