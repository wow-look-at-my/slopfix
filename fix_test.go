// A generator writes its output again on the next run, so no repair lands
// there. Joining the marker line with the next one would also stop tools from
// reading the file as generated.
func TestAGeneratedFileIsNeitherRepairedNorReported(t *testing.T) {
	src := "// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.28.0\n\npackage dbgen\n\n" +
		"// Prune used to read the flag.\n" + strings.Repeat("// It deletes a row that is stale on both clocks, and keeps the rest.\n", 16) +
		"func Prune() {}\n"
	for name, run := range map[string]func(slopfix.Request) slopfix.Repair{"fix": slopfix.Fix, "report": slopfix.Report} {
		repair := run(slopfix.Request{Content: src, Path: "dbgen/jobs.sql.gen.go"})
		assert.False(t, repair.Changed, name)
		assert.Equal(t, src, repair.Text, name)
		assert.Empty(t, repair.Kept, name)
		assert.Empty(t, repair.Findings, name)
	}

	// The same text without the marker is the author's own, and every rule reads it.
	own := strings.Replace(src, "// Code generated by sqlc. DO NOT EDIT.\n", "", 1)
	assert.NotEmpty(t, slopfix.Report(slopfix.Request{Content: own, Path: "dbgen/jobs.go"}).Kept)
}

// A document a generator writes carries the marker on its first line, and is
// exempt the way a generated source file is.
func TestAGeneratedDocumentIsNeitherRepairedNorReported(t *testing.T) {
	body := "There are three sections in the payload,\nand each one is read.\n"
	for path, marker := range map[string]string{
		"docs/api.md":     "<!-- Code generated by apidoc. DO NOT EDIT. -->\n",
		"docs/routes.txt": "# Code generated by buildhost routes. DO NOT EDIT.\n",
	} {
		src := marker + "\n" + body
		repair := slopfix.Fix(slopfix.Request{Content: src, Path: path})
		assert.False(t, repair.Changed, path)
		assert.Empty(t, slopfix.Report(slopfix.Request{Content: src, Path: path}).Findings, path)
		assert.Empty(t, slopfix.CheckContent(path, src), path)
		assert.True(t, slopfix.Fix(slopfix.Request{Content: body, Path: path}).Changed, "%s without the marker is the author's own", path)
	}
}

// A file .gitattributes marks linguist-generated needs no marker in its bytes.
// A route table a program renders and a CI gate compares is one: a joined line
// breaks the gate.
func TestAPathMarkedGeneratedIsNeitherRepairedNorReported(t *testing.T) {
	root := t.TempDir()
	out, err := exec.Command("git", "-C", root, "init", "-q").CombinedOutput()
	require.NoError(t, err, string(out))
	require.NoError(t, os.MkdirAll(filepath.Join(root, "docs"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, ".gitattributes"), []byte("docs/routes.txt linguist-generated\n"), 0o644))
	var table strings.Builder
	for _, route := range []string{"/", "/__signin", "/api/v1/projects", "/api/v1/tokens", "/llms.txt"} {
		table.WriteString(route + " {GET}\n")
	}
	path := filepath.Join(root, "docs", "routes.txt")
	require.NoError(t, os.WriteFile(path, []byte(table.String()), 0o644))

	assert.True(t, slopfix.Fix(slopfix.Request{Content: table.String(), Path: "routes.txt"}).Changed, "an unmarked table is joined like any paragraph")
	assert.Empty(t, slopfix.CheckContent(path, table.String()))
	assert.False(t, slopfix.Fix(slopfix.Request{Content: table.String(), Path: path}).Changed)
	tree := slopfix.FixTree(root)
	for _, finding := range tree.Findings {
		assert.NotEqual(t, path, finding.Path)
	}
	assert.NotContains(t, tree.Repaired, path)
	got, err := os.ReadFile(path)
	require.NoError(t, err)
	assert.Equal(t, table.String(), string(got))
}

